#!/usr/bin/env python3
"""gen_api_key.py TG_CONFIG OUT - the API keys as the binary carries them.

tg_config.h holds api_id and api_hash in plain text; compiled as they are,
`strings` on the app prints them. This writes them XOR-ed with a mask drawn
fresh for every build, and api_id.h undoes it when setTdlibParameters is
sent. It stops `strings` and a grep, not a debugger: TDLib needs the plain
values at runtime, so a hook on td_json_client_send still reads them.
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
api_id = re.search(r'^#define\s+TG_API_ID\s+(\d+)', text, re.M)
api_hash = re.search(r'^#define\s+TG_API_HASH\s+"([^"]*)"', text, re.M)
if not api_id or not api_hash:
    sys.exit('%s: TG_API_ID and TG_API_HASH are needed' % src)
value = int(api_id.group(1))
hash_bytes = api_hash.group(1).encode()
mask = os.urandom(len(hash_bytes))
id_mask = int.from_bytes(os.urandom(4), 'little')

def array(data):
    return ', '.join('0x%02x' % b for b in data)

body = '''// Generated by scripts/gen_api_key.py from tg_config.h. Do not commit.
#define TG_API_HASH_LEN %d
static const unsigned char kTGApiHashMasked[] = {%s};
static const volatile unsigned char kTGApiHashMask[] = {%s};
static const unsigned int kTGApiIdMasked = 0x%08xu;
static const volatile unsigned int kTGApiIdMask = 0x%08xu;
''' % (len(hash_bytes), array(bytes(a ^ b for a, b in zip(hash_bytes, mask))), array(mask),
       value ^ id_mask, id_mask)
tmp = out + '.tmp'
open(tmp, 'w').write(body)
os.replace(tmp, out)
