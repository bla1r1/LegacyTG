#!/usr/bin/env python3
"""Write src/Views/Icons/TGIconPaths.m from scripts/icon_picks.txt.

  scripts/gen_icon_paths.py [<@mdi/js package dir> <@fortawesome/fontawesome-free package dir>]

Each line of the picks file is `row name source glyph`, source being mdi, fa,
official, svg or ours (ours stays drawn by TGIcons and is skipped here).

  official <Set/Name>       a PDF in official_ref/Images.xcassets
  svg <w> <h> <d>           a path written by hand

Without the package dirs the mdi and fa rows reuse the path strings already in
TGIconPaths.m, so the catalogue can be regenerated with no network.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import official_icon

OUT = os.path.join(ROOT, 'src', 'Views', 'Icons', 'TGIconPaths.m')

mdi_dir = sys.argv[1] if len(sys.argv) > 1 else None
fa_dir = sys.argv[2] if len(sys.argv) > 2 else None
mdi_js = None
if mdi_dir:
    with open(os.path.join(mdi_dir, 'mdi.js')) as handle:
        mdi_js = handle.read()


def mdi(name):
    if not mdi_js:
        sys.exit('mdi package dir required for new mdi row ' + name)
    m = re.search(r'export var %s = "([^"]+)"' % re.escape(name), mdi_js)
    if not m:
        sys.exit('no MDI icon ' + name)
    return m.group(1), 24, 24, 0


def fa(name):
    if not fa_dir:
        sys.exit('Font Awesome package dir required for new fa row ' + name)
    for style in ('solid', 'regular'):
        path = os.path.join(fa_dir, 'svgs', style, name + '.svg')
        if os.path.exists(path):
            with open(path) as handle:
                svg = handle.read()
            w, h = re.search(r'viewBox="0 0 (\d+) (\d+)"', svg).groups()
            d = re.search(r'<path[^>]+d="([^"]+)"', svg).group(1)
            # MDI draws inside 20 of its 24 units; FA fills its box, so it
            # gets the same margin (in 24ths) to sit at the same size.
            return d, int(w), int(h), 2
    sys.exit('no Font Awesome icon ' + name)


def existing_paths():
    """name -> (d, w, h, pad) from the file this script is about to replace."""
    rows = {}
    if not os.path.exists(OUT):
        return rows
    with open(OUT) as handle:
        text = handle.read()
    pattern = re.compile(
            r'\{"([^"]+)", (\d+), (\d+), (\d+), "([^"]*)"\},')
    for m in pattern.finditer(text):
        rows[m.group(1)] = (m.group(5), int(m.group(2)),
                            int(m.group(3)), int(m.group(4)))
    return rows


rows, seen = [], set()
old = existing_paths()
with open(os.path.join(ROOT, 'scripts', 'icon_picks.txt')) as picks:
    for line in picks:
        parts = line.split()
        if len(parts) < 3 or line.startswith('#') or parts[2] == 'ours':
            continue
        name, source = parts[1], parts[2]
        if name in seen:
            continue
        seen.add(name)
        if source == 'mdi':
            glyph = parts[3]
            if not mdi_dir and name in old:
                d, w, h, pad = old[name]
            else:
                d, w, h, pad = mdi(glyph)
        elif source == 'fa':
            glyph = parts[3]
            if not fa_dir and name in old:
                d, w, h, pad = old[name]
            else:
                d, w, h, pad = fa(glyph)
        elif source == 'official':
            glyph = ' '.join(parts[3:])
            d, w, h = official_icon.icon_path(glyph)
            pad = 0
        elif source == 'svg':
            if len(parts) < 6:
                sys.exit('svg row needs <w> <h> <d>: ' + line)
            w, h = int(parts[3]), int(parts[4])
            d = ' '.join(parts[5:])
            pad = 0
            glyph = 'hand'
        else:
            sys.exit('unknown source ' + source + ' in ' + line)
        rows.append((name, d, w, h, pad, source, glyph))

out = ['// Generated by scripts/gen_icon_paths.py from scripts/icon_picks.txt - do not edit.',
       '// Material Design Icons: Apache 2.0. Font Awesome Free 6.5.1 icons: CC BY 4.0.',
       '// Official Telegram icons: official_ref/Images.xcassets (read-only).',
       '#import "TGIconPaths.h"', '#include <string.h>', '',
       'static const TGIconPath kPaths[] = {']
for name, d, w, h, pad, source, glyph in sorted(rows):
    out.append('\t{"%s", %d, %d, %d, "%s"},   // %s %s' % (
            name, w, h, pad, d, source, glyph))
out += ['};', '',
        'const TGIconPath *TGIconPathNamed(const char *name) {',
        '\tif (!name)', '\t\treturn NULL;',
        '\tfor (size_t i = 0; i < sizeof(kPaths) / sizeof(kPaths[0]); i++)',
        '\t\tif (strcmp(kPaths[i].name, name) == 0)',
        '\t\t\treturn &kPaths[i];',
        '\treturn NULL;', '}', '',
        'size_t TGIconPathCount(void) {',
        '\treturn sizeof(kPaths) / sizeof(kPaths[0]);', '}', '',
        'const TGIconPath *TGIconPathAt(size_t index) {',
        '\treturn index < TGIconPathCount() ? &kPaths[index] : NULL;', '}', '']
open(OUT, 'w').write('\n'.join(out))
print(len(rows), 'icons')
